def exp_main(params, data_states, pools):
    f_true, sim_true = osdr_funcs(params)
    fit = fit_from(f_true, pools.train[:DEFAULT_N_TRAJ], pools.val)
    res = evaluate(f_true, sim_true, fit, pools, data_states)
    train_states = np.vstack(fit.trajs)

    print("=" * 30, f"SINDy ODE ({DEFAULT_N_TRAJ} trajectories x t_len {DEFAULT_T_LEN:g}, dt {DT:g})", "=" * 30)
    print("threshold selection (validation error of the vector field, number of terms):")
    for th, err, n in fit.sweep:
        print(f"    threshold {th:.0e}: val. error {err:.4f}, {n} terms" + ("   <- chosen" if th == fit.threshold else ""))
    print()
    print(fit.ode.format(), "\n")

    ref = least_squares_reference(params, train_states)
    comparisons = {
        "coefficients": compare_coefficients(fit.ode, ref, "main"),
        "vector_field": compare_vector_field(f_true, fit.ode, train_states[::10], data_states),
        "interactions": compare_interactions(f_true, fit.ode, data_states),
        "origin": compare_origin(params, fit.ode),
        "behaviour": compare_behaviour(params, fit.ode, res),
    }

    s, g = res["sol_true"], res["sol_sindy"]
    fig, ax = plt.subplots(figsize=(8, 4))
    plot_overlay_timeseries(ax, s, g)
    ax.legend(frameon=False, ncol=2, loc="upper right")
    ax.set_title("Fig. 4f initial state (out-of-sample): OSDR (solid) vs SINDy (dashed)")
    save(fig, "part3_main_timeseries.png")

    lims = [(0, max(np.nanmax(s[:, i]), np.nanmax(g[:, i])) * 1.05) for i in range(3)]
    save(plot_3d_trajectory(s, CELL_TYPES, "OSDR ODE (Fig. 4f)", lims=lims), "part3_main_3d_osdr.png")
    save(plot_3d_trajectory(g, CELL_TYPES, "SINDy ODE", color="#E4572E", lims=lims), "part3_main_3d_sindy.png")
    save(plot_projections(s, g, "2D projections of the Fig. 4f trajectory"), "part3_main_projections.png")

    settings = {"n_traj": len(fit.trajs), "n_initial_states": DEFAULT_N_TRAJ, "t_len": DEFAULT_T_LEN, "dt": DT,
                "threshold": fit.threshold, "sweep": fit.sweep, "state_scale": STATE_SCALE}
    path = write_ode_comparison(RESULTS_DIR / "main_ode_comparison.md", params, fit.ode, ref, res, comparisons, settings)
    print(f"ODE comparison report: {path}\n")


def exp_length(params, data_states, pools):
    f_true, sim_true = osdr_funcs(params)
    lengths = [25, 50, 100, 200, 400, 800, 1600, 3200]
    rows = {}
    for t_len in lengths:
        fit = fit_from(f_true, pools.train[:DEFAULT_N_TRAJ], pools.val, t_len=t_len)
        rows[t_len] = evaluate(f_true, sim_true, fit, pools, data_states)

    print("=" * 30, f"length of each training time series ({DEFAULT_N_TRAJ} trajectories)", "=" * 30)
    df = metrics_table(rows, "t_len")
    print_df(df)

    fig, axs = plt.subplots(2, 3, figsize=(14, 7))
    plot_metric_curves(axs[0], df, "length of each training time series (t_len)")
    for ax, t_len in zip(axs[1], [100, 400, 1600]):
        plot_overlay_timeseries(ax, rows[t_len]["sol_true"], rows[t_len]["sol_sindy"])
        ax.set_title(f"t_len = {t_len}")
        ax.get_legend().remove()
    axs[1, 2].legend(frameon=False, ncol=2, fontsize=7, loc="upper right")
    fig.suptitle("SINDy vs. length of the training time series (Fig. 4f initial state; solid OSDR, dashed SINDy)")
    save(fig, "part3_length.png")


def exp_ntraj(params, data_states, pools):
    f_true, sim_true = osdr_funcs(params)
    rows = {}
    # only the Fig. 4f trajectory (in-sample for the Fig. 4f comparison!):
    rows["Fig. 4f only"] = evaluate(f_true, sim_true, fit_from(f_true, FIG4F_X0[None, :], pools.val), pools, data_states)
    for n in [1, 3, 10, 30, 100, 300]:
        rows[n] = evaluate(f_true, sim_true, fit_from(f_true, pools.train[:n], pools.val), pools, data_states)

    print("=" * 30, f"number of training trajectories (t_len {DEFAULT_T_LEN:g})", "=" * 30)
    df = metrics_table(rows, "n_traj")
    print_df(df)

    fig, axs = plt.subplots(2, 3, figsize=(14, 7))
    plot_metric_curves(axs[0], df.drop(index="Fig. 4f only"), "number of training trajectories")
    for ax, key in zip(axs[1], ["Fig. 4f only", 10, 100]):
        plot_overlay_timeseries(ax, rows[key]["sol_true"], rows[key]["sol_sindy"])
        ax.set_title(f"training: {key}" + (" trajectories" if key != "Fig. 4f only" else ""))
        ax.get_legend().remove()
    axs[1, 2].legend(frameon=False, ncol=2, fontsize=7, loc="upper right")
    fig.suptitle("SINDy vs. number of training trajectories (solid OSDR, dashed SINDy)")
    save(fig, "part3_ntraj.png")


def exp_params(params, data_states, pools):
    variants = {
        "fitted model": params,
        "p- x 0.9": with_death_scale(params, 0.9),
        "p- x 1.25": with_death_scale(params, 1.25),
        "B->T x 0": with_b_inhibition_scale(params, 0.0),
        "B->T x 2": with_b_inhibition_scale(params, 2.0),
    }
    rows = {}
    for name, p in variants.items():
        f_true, sim_true = osdr_funcs(p)
        fit = fit_from(f_true, pools.train[:DEFAULT_N_TRAJ], pools.val)
        rows[name] = evaluate(f_true, sim_true, fit, pools, data_states)
        rows[name]["threshold_cd4"] = (
            excitability_threshold(sim_true),
            excitability_threshold(lambda x0, t: fit.ode.simulate(x0, t)),
        )

    print("=" * 30, "SINDy for different OSDR parameters", "=" * 30)
    print_df(metrics_table(rows, "variant"))
    for name, r in rows.items():
        print(f"    {name:12s} excitability threshold CD4(0): OSDR {r['threshold_cd4'][0]:.1f}  SINDy {r['threshold_cd4'][1]:.1f}")
    print()

    fig, axs = plt.subplots(1, len(variants), figsize=(4 * len(variants), 3.6), sharey=True)
    for ax, (name, r) in zip(axs, rows.items()):
        plot_overlay_timeseries(ax, r["sol_true"], r["sol_sindy"])
        ax.set_title(f"{name}\nFig. 4f err {r['fig4f_err']:.2f}")
        ax.get_legend().remove()
    axs[-1].legend(frameon=False, ncol=1, fontsize=7, bbox_to_anchor=(1.02, 1), loc="upper left")
    fig.suptitle("OSDR (solid) vs SINDy (dashed) for modified OSDR parameters")
    save(fig, "part3_params.png")


def exp_control(params, data_states, pools):
    """Ground truth that SINDy CAN represent: the LS cubic approximation of the OSDR vector field."""
    f_osdr, _ = osdr_funcs(params)
    trajs, _ = make_training_data(lambda x: f_osdr(x)[0], pools.train[:DEFAULT_N_TRAJ], DEFAULT_T_LEN, DT)
    truth = least_squares_reference(params, np.vstack(trajs), label="polynomial truth")

    f_poly = truth.rhs
    sim_poly = truth.simulate
    fit_poly = fit_from(f_poly, pools.train[:DEFAULT_N_TRAJ], pools.val)
    res_poly = evaluate(f_poly, sim_poly, fit_poly, pools, data_states)

    fit_osdr = fit_from(f_osdr, pools.train[:DEFAULT_N_TRAJ], pools.val)
    res_osdr = evaluate(f_osdr, lambda x0, t: simulate(params, x0, t), fit_osdr, pools, data_states)

    A, B = scaled_coefficients(fit_poly.ode), scaled_coefficients(truth)
    C = scaled_coefficients(fit_osdr.ode)

    print("=" * 30, "control: polynomial ground truth vs OSDR ground truth", "=" * 30)
    print(f"  truth = polynomial ODE (LS cubic fit of OSDR, {np.count_nonzero(truth.coef)} terms)")
    print(f"    coefficient error  ||SINDy - truth|| / ||truth|| (scaled): {np.linalg.norm(A - B) / np.linalg.norm(B):.4f}")
    print(f"  truth = OSDR ODE (sigmoid, not in the library)")
    print(f"    coefficient error  ||SINDy - LS reference|| / ||LS reference||: {np.linalg.norm(C - B) / np.linalg.norm(B):.4f}")
    print()
    print_df(metrics_table({"polynomial truth": res_poly, "OSDR truth": res_osdr}, "ground truth"))

    fig, axs = plt.subplots(1, 2, figsize=(13, 4), sharey=True)
    for ax, (name, r) in zip(axs, [("polynomial truth", res_poly), ("OSDR truth", res_osdr)]):
        plot_overlay_timeseries(ax, r["sol_true"], r["sol_sindy"], label_true="truth")
        ax.set_title(f"ground truth: {name}  (Fig. 4f err {r['fig4f_err']:.3f})")
        ax.get_legend().remove()
    axs[1].legend(frameon=False, ncol=2, fontsize=7, loc="upper right")
    save(fig, "part3_control.png")


def plot_metric_curves(axs, df: pd.DataFrame, xlabel: str):
    x = np.arange(len(df))
    fig4f = df["fig4f_err"].astype(float).replace(np.inf, np.nan)
    test = df["test_median_err"].astype(float).replace(np.inf, np.nan)

    ax = axs[0]
    ax.plot(x, fig4f, "o-", label="Fig. 4f trajectory")
    ax.plot(x, test, "s-", label=f"median of {N_TEST} held-out")
    for xi, v in zip(x, df["fig4f_err"].astype(float)):
        if not np.isfinite(v):
            ax.annotate("escaped", (xi, 0), textcoords="offset points", xytext=(0, 5), ha="center", fontsize=7, color="red")
    ax.set_ylabel("relative trajectory error")
    ax.set_yscale("log")
    ax.legend(frameon=False)

    ax = axs[1]
    ax.plot(x, df["vf_train"].astype(float), "o-", label="training states")
    ax.plot(x, df["vf_data"].astype(float), "s-", label="observed data states")
    ax.set_ylabel("relative vector-field error")
    ax.set_yscale("log")
    ax.legend(frameon=False)

    ax = axs[2]
    ax.plot(x, df["n_terms"].astype(float), "o-", color="gray")
    ax.set_ylabel("number of terms kept")

    for ax in axs:
        ax.set_xticks(x, [str(i) for i in df.index], rotation=45)
