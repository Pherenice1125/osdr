def plot_overlay_timeseries(ax, s_true, s_est, t_max=2500, label_true="OSDR", label_est="SINDy"):
    mask = T_TEST <= t_max
    plot_timeseries(ax, T_TEST[mask], s_true[mask], CELL_TYPES, CELL_COLORS, label_suffix=f" ({label_true})")
    plot_timeseries(ax, T_TEST[mask], s_est[mask], CELL_TYPES, CELL_COLORS, linestyle="--",
                    label_suffix=f" ({label_est})")


def plot_projections(s_true, s_est, title, label_true="OSDR", label_est="SINDy"):
    fig, axs = plt.subplots(1, 3, figsize=(13, 4))
    for ax, (i, j) in zip(axs, PROJECTIONS):
        ax.plot(s_true[:, i], s_true[:, j], color="#3B76BC", lw=2.5, label=label_true)
        ax.plot(s_est[:, i], s_est[:, j], color="#E4572E", lw=2, ls="--", label=label_est)
        ax.scatter(*s_true[0, [i, j]], color="#6BBF59", s=50, zorder=5, label="start")
        ax.set_xlabel(CELL_TYPES[i])
        ax.set_ylabel(CELL_TYPES[j])
        ax.set_title(f"{CELL_TYPES[i]} - {CELL_TYPES[j]} plane")
        ax.spines[["top", "right"]].set_visible(False)
    axs[0].legend(frameon=False)
    fig.suptitle(title)
    return fig


