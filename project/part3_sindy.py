@dataclass
class Pools:
    train: np.ndarray
    val: np.ndarray
    test: np.ndarray


def initial_state_pools(states: np.ndarray, seed: int = SEED) -> Pools:
    """Disjoint random sets of observed neighbourhood compositions used as initial states."""
    idx = np.random.default_rng(seed).permutation(len(states))
    test = states[idx[:N_TEST]] # 20 rows
    val = states[idx[N_TEST : N_TEST + N_VAL]] # 20 rows
    train = states[idx[N_TEST + N_VAL :]] # remaining(4960) rows
    return Pools(train=train, val=val, test=test)


@dataclass
class Fit:
    ode: PolyODE
    threshold: float
    sweep: list[tuple[float, float, int]]
    trajs: list[np.ndarray]


def fit_from(f_vec, x0s_train, x0s_val, t_len: float = DEFAULT_T_LEN) -> Fit:
    """Generate training / validation time series from dx/dt = f_vec(x) and fit SINDy."""
    f = lambda x: f_vec(x)[0]  # noqa: E731
    trajs, _ = make_training_data(f, x0s_train, t_len, DT)
    val_trajs, _ = make_training_data(f, x0s_val, t_len, DT)
    V = np.vstack(val_trajs)[::5]
    ode, th, sweep = fit_sindy_select_threshold(trajs, DT, V, f_vec(V))
    return Fit(ode, th, sweep, trajs)


def evaluate(f_true_vec, simulate_true, fit: Fit, pools: Pools, data_states: np.ndarray) -> dict:
    """Vector-field, trajectory and threshold metrics of a SINDy fit against the true ODE."""
    ode = fit.ode
    train_states = np.vstack(fit.trajs)[::10]

    sol_true = simulate_true(FIG4F_X0, T_TEST)
    sol_sindy = ode.simulate(FIG4F_X0, T_TEST)

    test_errs = [trajectory_error(simulate_true(x0, T_TEST), ode.simulate(x0, T_TEST)) for x0 in pools.test]
    test_errs = np.array(test_errs)

    return {
        "n_terms": ode.n_terms,
        "threshold": fit.threshold,
        "vf_train": vector_field_errors(f_true_vec, ode.rhs, train_states)["rel_err"],
        "vf_data": vector_field_errors(f_true_vec, ode.rhs, data_states)["rel_err"],
        "cos_data": vector_field_errors(f_true_vec, ode.rhs, data_states)["mean_cosine"],
        "fig4f_err": trajectory_error(sol_true, sol_sindy),
        "test_median_err": float(np.median(test_errs)),
        "test_escaped": float(np.mean(~np.isfinite(test_errs))),
        "sol_true": sol_true,
        "sol_sindy": sol_sindy,
    }


def metrics_table(rows: dict, index_name: str) -> pd.DataFrame:
    cols = ["n_terms", "threshold", "vf_train", "vf_data", "cos_data", "fig4f_err", "test_median_err", "test_escaped"]
    df = pd.DataFrame({k: {c: v[c] for c in cols} for k, v in rows.items()}).T
    df.index.name = index_name
    return df


def print_df(df: pd.DataFrame):
    with pd.option_context(
        "display.float_format", "{:.3g}".format, "display.width", 200, "display.max_columns", None
    ):
        print(df, "\n")


def osdr_funcs(params):
    return (lambda X: rhs(params, X)), (lambda x0, t: simulate(params, x0, t))


